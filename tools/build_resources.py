"""Build what the installer copies from defs/*.json.

Writes chriz-bg-magic/res/ (the files), chriz-bg-magic/lib/cbmagic_resources.tpa (one COPY per file,
filling in what only the install can know) and chriz-bg-magic/languages/english/resources.tra.

usage: python tools/build_resources.py [--out FOLDER]
With --out the same three go below FOLDER instead of chriz-bg-magic/.
"""
import argparse
import json
import shutil
from pathlib import Path

import resformat as rf

ROOT = Path(__file__).resolve().parent.parent
DEFS = ROOT / "defs"
MOD = ROOT / "chriz-bg-magic"
FIRST_STRING = 70000
# Pierce Magic's and Lesser Restoration's new rules are EEex callbacks, which do nothing without
# EEex. There the game's spells and scroll stay, and the log says so.
NEEDS_EEEX = ("spwi608.spl", "scrl7l.itm", "sppr417.spl")


class Strings:
    def __init__(self):
        self.numbers = {}

    def number(self, text):
        return self.numbers.setdefault(text, FIRST_STRING + len(self.numbers))

    def tra(self):
        lines = []
        for text, number in self.numbers.items():
            mark = "~" if "~" not in text else "~~~~~"
            lines.append(f"@{number} = {mark}{text}{mark}")
        return "\n".join(lines) + "\n"


def var(value):
    """The WeiDU variable that holds a symbol's value at install."""
    if "state" in value:
        return "cbm_state_" + value["state"]
    if "splprot" in value:
        return "cbm_prot_" + "_".join(str(v).replace("-", "m") for v in value["splprot"])
    if "sectype" in value:
        return value["sectype"]
    if "statdesc" in value:
        return f"cbm_stat_{value['statdesc']}"
    if "projectile" in value:
        return f"cbm_proj_{value['projectile']}"
    raise ValueError(value)


def write_op(kind):
    return {"i": "WRITE_LONG", "I": "WRITE_LONG", "H": "WRITE_SHORT", "h": "WRITE_SHORT", "B": "WRITE_BYTE"}[kind]


def stamp_line(stamp, strings):
    offset, value = f"0x{stamp['offset']:x}", stamp["value"]
    if "text" in value:
        say = f"SAY {offset} @{strings.number(value['text'])}"
        if "old" in value:
            # Other languages keep the game's own text until a translation exists.
            return f"    WRITE_LONG {offset} {value['old']}\n    PATCH_IF cbm_english BEGIN {say} END"
        return f"    {say}"
    if "spell" in value:
        return f"    WRITE_ASCIIE {offset} ~%cbm_res_{value['spell']}%~ #8"
    return f"    {write_op(stamp['kind'])} {offset} {var(value)}"


def build(target=MOD):
    strings = Strings()
    res = target / "res"
    shutil.rmtree(res, ignore_errors=True)
    res.mkdir(parents=True)
    tables = json.loads((DEFS / "tables.json").read_text(encoding="utf-8"))
    added = {t["file"]: s for s, t in tables["spells"].items()}
    states, prots = set(), {}
    blocks, added_blocks = [], []
    for path in sorted(DEFS.glob("*.json")):
        if path.name == "tables.json":
            continue
        name = path.stem.lower()
        defn = json.loads(path.read_text(encoding="utf-8"))
        data, stamps = rf.build_resource(defn)
        (res / name).write_bytes(data)
        lines = []
        for stamp in stamps:
            value = stamp["value"]
            if "state" in value:
                states.add(value["state"])
            if "splprot" in value:
                prots[var(value)] = value["splprot"]
            lines.append(stamp_line(stamp, strings))
        if name in added:
            symbol = added[name]
            added_blocks.append((name, symbol, lines))
            continue
        block = "\n".join([f"  COPY ~chriz-bg-magic/res/{name}~ ~override/{name}~", *lines])
        if name in NEEDS_EEEX:
            block = (f"  ACTION_IF FILE_EXISTS_IN_GAME ~M___EEex.lua~ BEGIN\n{block}\n  END ELSE BEGIN\n"
                     f"    PRINT ~chriz-bg-magic: {name} stays as it is: its new rule needs EEex.~\n  END")
        blocks.append(block)

    out = ["// Generated by tools/build_resources.py from defs/. Do not edit.",
           "// Every file overwrites what stood there. Nothing here reads the old content.", ""]
    out.append("DEFINE_ACTION_FUNCTION cbmagic_write_resources\nBEGIN")
    out.append("  LAF cbmagic_game_language RET lang END")
    out.append("  OUTER_SET cbm_english = 0")
    out.append("  ACTION_IF (~%lang%~ STRING_EQUAL ~en_us~) BEGIN OUTER_SET cbm_english = 1 END ELSE BEGIN")
    out.append("    PRINT ~chriz-bg-magic: descriptions exist only in English so far; this game (%lang%) keeps its own.~")
    out.append("  END")
    out.append("  // Files without anything to fill in.")
    out.append("  COPY ~chriz-bg-magic/files~ ~override~")
    out.append("  // Rows and numbers of this install.")
    for key, (stat, value, relation) in sorted(prots.items()):
        out.append(f"  LAF cbmagic_splprot_row INT_VAR stat = {stat} value = {value} relation = {relation} RET {key} = row END")
    for state in sorted(states):
        out.append(f"  LAF cbmagic_state_value STR_VAR symbol = ~{state}~ RET cbm_state_{state} = state END")
    for name, text in tables["sectypes"].items():
        out.append(f"  ADD_SECTYPE ~{name}~ " + (f"@{strings.number(text)}" if text else "~~"))
    for name in tables["projectiles"]:
        out.append(f"  ADD_PROJECTILE ~chriz-bg-magic/pro/{name}.pro~")
        out.append(f"  OUTER_SET cbm_proj_{name} = {name}")
    for row, entry in sorted(tables["statdesc"].items(), key=lambda kv: int(kv[0])):
        out.append(f"  OUTER_SET ref = RESOLVE_STR_REF (@{strings.number(entry['text'])})")
        out.append(f"  LAF cbmagic_statdesc_row INT_VAR desc_ref = ref STR_VAR bam = ~{entry['bam']}~ RET cbm_stat_{row} = icon_row END")
    for row, entry in sorted(tables["statdesc_changed"].items(), key=lambda kv: int(kv[0])):
        out.append(f"  OUTER_SET ref = RESOLVE_STR_REF (@{strings.number(entry['text'])})")
        out.append(f"  LAF cbmagic_statdesc_text INT_VAR row = {row} text = ref END")
    out.append("  APPEND ~spell.ids~ ~2510 WIZARD_DISPELLING_SCREEN~ UNLESS ~WIZARD_DISPELLING_SCREEN~")
    out.append("  // Spells of our own, in the slot this install has free.")
    for symbol, entry in sorted(tables["spells"].items()):
        out.append(f"  ADD_SPELL ~chriz-bg-magic/res/{entry['file']}~ {entry['type']} {entry['level']} ~{symbol}~")
        out.append(f"  LAF cbmagic_spell_resref STR_VAR symbol = ~{symbol}~ RET cbm_res_{symbol} = resref END")
    for name, symbol, lines in added_blocks:
        out.append(f"  COPY_EXISTING ~%cbm_res_{symbol}%.spl~ ~override~")
        out.extend(lines)
    out.append("  // Spells and items, overwritten.")
    out.extend(blocks)
    out.append("END\n")
    tpa = target / "lib" / "cbmagic_resources.tpa"
    tra = target / "languages" / "english" / "resources.tra"
    tpa.parent.mkdir(parents=True, exist_ok=True)
    tra.parent.mkdir(parents=True, exist_ok=True)
    tpa.write_text("\n".join(out), encoding="utf-8", newline="\n")
    tra.write_text(strings.tra(), encoding="utf-8", newline="\n", errors="surrogateescape")
    return len(blocks) + len(added_blocks), len(strings.numbers)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=MOD)
    resources, strings = build(ap.parse_args().out)
    print(f"{resources} resources, {strings} strings")


if __name__ == "__main__":
    main()
