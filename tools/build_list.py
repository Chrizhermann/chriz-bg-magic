"""Exports Christopher's decisions as docs/build-list.json.

usage: python -I tools/build_list.py <snapshot folder> [--rows tools/rows.json]
                                     [--specs docs/build-specs.json] [--out docs/build-list.json]

The snapshot folder is a copy of the decision page's database: entscheidungen/<row id>.json
with the fields wahl, notiz and zeit. Only the decision (wahl) and its time are exported;
the notes (notiz) are Christopher's own chat remarks and stay out of the repo. Names,
levels and vanilla resrefs come from tools/rows.json (tools/make_rows.py), the English
specs and build status of the rows already built from docs/build-specs.json.
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

MEANINGS = {
    "vanilla": "the spell stays vanilla",
    "drop": "Spell Revisions' change is dropped: the spell stays vanilla, plus any fix the decision names",
    "scs": "like SCS's version, built ourselves",
    "keep": "build the page's proposal",
    "asdecided": "as decided in chat",
    "rethink": "still open: do not build",
}
IWD_MEANINGS = {
    "keep": "take the IWD spell",
    "rethink": "adjust the IWD spell (still open)",
    "drop": "leave the IWD spell out",
}
STATUS_ORDER = ["open", "todo", "done", "lab-checked"]


def overall(parts):
    return min((p["status"] for p in parts), key=STATUS_ORDER.index) if parts else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("snapshot", type=Path)
    ap.add_argument("--rows", type=Path, default=REPO / "tools/rows.json")
    ap.add_argument("--specs", type=Path, default=REPO / "docs/build-specs.json")
    ap.add_argument("--out", type=Path, default=REPO / "docs/build-list.json")
    args = ap.parse_args()

    folder = args.snapshot / "entscheidungen"
    if not folder.is_dir():
        sys.exit(f"no entscheidungen folder in {args.snapshot}")
    meta = json.loads(args.rows.read_text(encoding="utf-8"))
    specs = json.loads(args.specs.read_text(encoding="utf-8")) if args.specs.exists() else {}
    row_specs = specs.get("rows", {})

    rows, unknown, bad = [], [], []
    for f in sorted(folder.glob("*.json")):
        rid = f.stem
        doc = json.loads(f.read_text(encoding="utf-8"))
        choice = doc.get("wahl")
        meanings = IWD_MEANINGS if rid.startswith("iwd.") else MEANINGS
        if choice not in meanings:
            bad.append(f"{rid}: {choice!r}")
            continue
        m = meta.get(rid)
        if m is None:
            unknown.append(rid)
            m = {"name": None, "group": rid.rsplit(".", 1)[0], "level": None, "source": None, "resrefs": []}
        spec = row_specs.get(rid, {})
        entry = {"id": rid, "name": m["name"], "group": m["group"], "level": m["level"], "source": m["source"],
                 "resrefs": spec.get("resrefs", m["resrefs"]), "decision": choice, "decided_at": doc.get("zeit")}
        parts = spec.get("parts", [])
        if parts:
            entry["parts"] = parts
        entry["status"] = overall(parts) or ("open" if choice == "rethink" else "todo")
        rows.append(entry)
    for rid in row_specs:
        if not (folder / f"{rid}.json").exists():
            sys.exit(f"docs/build-specs.json names {rid}, which the snapshot does not have")
    chat = []
    for c in specs.get("chat", []):
        chat.append({**c, "status": overall(c.get("parts", [])) or "todo"})

    out = {
        "about": "Christopher's decisions for chriz-bg-magic, one entry per row of his decision page. "
                 "Generated by tools/build_list.py; do not edit by hand.",
        "snapshot": args.snapshot.name,
        "decisions": MEANINGS,
        "iwd_decisions": IWD_MEANINGS,
        "status": {"open": "still undecided, not to be built", "todo": "decided, not built yet",
                   "done": "built", "lab-checked": "built, installed in a disposable lab and checked there "
                                                   "(docs/evidence names what was checked in play)"},
        "rows": rows,
        "chat_decisions": chat,
    }
    args.out.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    counts = {}
    for r in rows:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    print(f"{len(rows)} rows {counts}, {len(chat)} chat decisions -> {args.out}")
    if unknown:
        print(f"warning: {len(unknown)} rows missing from {args.rows.name}: {', '.join(unknown)}")
    if bad:
        sys.exit("unknown decision values: " + "; ".join(bad))


if __name__ == "__main__":
    main()
